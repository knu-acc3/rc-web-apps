/** The 16 colors of HTML 4 / CSS 1. */
export const CSS1_COLORS = new Set(["aqua", "black", "blue", "fuchsia", "gray", "green", "lime", "maroon", "navy", "olive", "purple", "red", "silver", "teal", "white", "yellow"]);

/** Where a name comes from, for the facts block. */
export function origin(name: string): { ru: string; en: string } {
  if (CSS1_COLORS.has(name)) return { ru: "CSS 1 / HTML 4 (16 базовых цветов)", en: "CSS 1 / HTML 4 (the 16 basic colors)" };
  if (name === "orange") return { ru: "CSS 2.1 (2011)", en: "CSS 2.1 (2011)" };
  if (name === "rebeccapurple") return { ru: "CSS Color 4 (2014), в память о Ребекке Мейер", en: "CSS Color 4 (2014), in memory of Rebecca Meyer" };
  return { ru: "CSS Color 3 (список цветов X11 / SVG 1.0)", en: "CSS Color 3 (X11 / SVG 1.0 color list)" };
}
