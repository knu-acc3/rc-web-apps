// Tailwind CSS v4 default palette (OKLCH) → src/tools/design/color/design/data/tailwind-v4.ts
// Source: node_modules/tailwindcss/theme.css of the installed Tailwind version.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const require = createRequire(join(root, "package.json"));
const pkgPath = require.resolve("tailwindcss/package.json");
const version = JSON.parse(readFileSync(pkgPath, "utf8")).version;
const css = readFileSync(join(dirname(pkgPath), "theme.css"), "utf8");

const STEPS = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "950"];
const families = new Map();
for (const m of css.matchAll(/--color-([a-z]+)-(\d+):\s*(oklch\([^)]*\));/g)) {
  const [, fam, step, value] = m;
  if (!families.has(fam)) families.set(fam, {});
  families.get(fam)[step] = value;
}
const lines = [];
for (const [fam, shades] of families) {
  if (STEPS.some((s) => !shades[s])) throw new Error(`Incomplete family ${fam}`);
  lines.push(`  ${fam}: [${STEPS.map((s) => JSON.stringify(shades[s])).join(", ")}],`);
}
const out = `// Generated by scripts/data/gen-color-tailwind.mjs from tailwindcss@${version} theme.css — do not edit.
/** Tailwind CSS v4 default palette: OKLCH values for shades 50–950. */
export const TAILWIND_V4_VERSION = ${JSON.stringify(version)};
export const TAILWIND_V4: Readonly<Record<string, readonly string[]>> = {
${lines.join("\n")}
};
`;
writeFileSync(join(root, "src/tools/design/color/design/data/tailwind-v4.ts"), out);
console.log(`tailwind v4 ${version}: ${families.size} families`);
