// Generates src/sections/tool-components.ts: one next/dynamic() per tool component.
// next/dynamic with an inline import() lets the server preload exactly the chunk of the tool a page
// renders, so the tool is interactive as soon as the page hydrates. Source of truth: the
// `components` maps in src/sections/<id>/components.ts (and the files they spread in).
// Runs before every build (npm prebuild); tests check that the output is up to date.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const sectionsDir = join(root, "src", "sections");

function resolveTs(from, spec) {
  const base = resolve(dirname(from), spec);
  for (const ext of [".ts", ".tsx", "/index.ts"]) if (existsSync(base + ext)) return base + ext;
  return null;
}

/** Collect "id" → import specifier (as "@/..." path) from a component map file and the maps it spreads in. */
function collect(file, out) {
  const src = readFileSync(file, "utf8");
  for (const m of src.matchAll(/"([^"]+)":\s*\(\)\s*=>\s*import\("([^"]+)"\)/g)) {
    const [, id, spec] = m;
    const target = spec.startsWith(".") ? "@/" + relative(join(root, "src"), resolve(dirname(file), spec)).replace(/\\/g, "/") : spec;
    out.set(id, target);
  }
  for (const m of src.matchAll(/^import\s+(?!type)[^;]*?from\s+"(\.[^"]+)";/gm)) {
    const f = resolveTs(file, m[1]);
    if (f) collect(f, out);
  }
}

const map = new Map();
for (const id of readdirSync(sectionsDir).sort()) {
  const f = join(sectionsDir, id, "components.ts");
  if (existsSync(f)) collect(f, map);
}

const lines = [...map].sort(([a], [b]) => a.localeCompare(b)).map(([id, spec]) => `  ${JSON.stringify(id)}: dynamic(() => import(${JSON.stringify(spec)})),`);
const out = `// Generated by scripts/gen-tool-components.mjs from the section component maps — do not edit.
"use client";

import dynamic from "next/dynamic";
import type { ComponentType } from "react";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
export const TOOL_COMPONENTS: Record<string, ComponentType<any>> = {
${lines.join("\n")}
};
`;
const target = join(sectionsDir, "tool-components.ts");
const prev = existsSync(target) ? readFileSync(target, "utf8") : "";
if (process.argv.includes("--check")) {
  if (prev !== out) {
    console.error("src/sections/tool-components.ts is out of date: run node scripts/gen-tool-components.mjs");
    process.exit(1);
  }
} else if (prev !== out) {
  writeFileSync(target, out);
  console.log(`tool-components: ${map.size} components`);
}
